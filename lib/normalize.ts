// تطبيع النص العربي لتحسين البحث الذكي.
// يوحّد أشكال الهمزة، ويزيل «ال» التعريف من بداية الكلمة، ويحذف التطويل
// والتشكيل، ويقلّص الفراغات، ويحوّل الحروف اللاتينية للأحرف الصغيرة.
// النتيجة: "اديداس" يطابق "أديداس"، و"الاديداس" يطابق "أديداس".

export function normalizeArabic(input: string | null | undefined): string {
  if (!input) return "";

  // الحروف اللاتينية للأحرف الصغيرة (لا يؤثر على العربية)
  let s = input.toLowerCase();

  // إزالة التطويل (ـ)
  s = s.replace(/ـ/g, "");

  // إزالة التشكيل (الفتحة/الضمة/الكسرة/الشدة/السكون... + الألف الخنجرية)
  s = s.replace(/[ً-ْٰ]/g, "");

  // توحيد الهمزة والألف: أ إ آ → ا، ؤ → و، ئ/ى → ي، ء تُحذف
  s = s
    .replace(/[آأإ]/g, "ا")
    .replace(/ؤ/g, "و")
    .replace(/[ئى]/g, "ي")
    .replace(/ء/g, "");

  // إزالة «ال» التعريف من بداية كل كلمة (مع إبقاء كلمات قصيرة كما هي)
  s = s
    .split(/\s+/)
    .map((w) =>
      w.length > 3 && w.startsWith("ال") ? w.slice(2) : w
    )
    .join(" ");

  // تقليص الفراغات + قصّ الأطراف
  return s.replace(/\s+/g, " ").trim();
}
